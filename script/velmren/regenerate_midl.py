#!/usr/bin/env python3
"""Regenerate COM outputs with the SDK; verify the compiler against baseline.

The existing IDL from HEAD is first compiled and compared byte-for-byte with its
checked-in outputs (ignoring Git newline conversion). This validates using MSVC preprocessing in place of the
Chromium clang-cl preprocessor while a source checkout is being prepared.
Chromium's midl.py performs its standard deterministic timestamp normalization.
"""
import argparse
import importlib.util
import os
from pathlib import Path
import shutil
import subprocess

ROOT = Path(__file__).resolve().parents[2]
IDL = Path('brave/chromium_src/chrome/elevation_service/elevation_service_idl.idl')
FILES = ['elevation_service_idl.h', 'elevation_service_idl_i.c',
         'elevation_service_idl_p.c', 'elevation_service_idl.dlldata.c',
         'elevation_service_idl.tlb']


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--sdk', required=True, type=Path)
    ap.add_argument('--sdk-version', required=True)
    ap.add_argument('--msvc', required=True, type=Path)
    ap.add_argument('--work-dir', required=True, type=Path)
    ap.add_argument('--chromium-midl', type=Path,
                    default=ROOT.parent/'build/toolchain/win/midl.py')
    args = ap.parse_args()
    args.work_dir = args.work_dir.resolve()
    spec = importlib.util.spec_from_file_location('chromium_midl', args.chromium_midl)
    midl_utils = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(midl_utils)
    env = dict(os.environ)
    sdk_include = args.sdk/'Include'/args.sdk_version
    sdk_bin = args.sdk/'bin'/args.sdk_version/'x64'
    compiler_bin = args.msvc/'bin/Hostx64/x64'
    env['INCLUDE'] = ';'.join(str(p) for p in
        [args.msvc/'include', sdk_include/'shared', sdk_include/'um', sdk_include/'ucrt'])
    env['PATH'] = f'{compiler_bin};{sdk_bin};' + env['PATH']
    env['TEMP'] = env['TMP'] = str(args.work_dir/'temp')
    Path(env['TEMP']).mkdir(parents=True, exist_ok=True)
    baseline_src = args.work_dir/'baseline/src'
    (baseline_src/'out/Static').mkdir(parents=True, exist_ok=True)
    (baseline_src/IDL).parent.mkdir(parents=True, exist_ok=True)
    baseline_idl = subprocess.check_output(
        ['git', 'show', 'HEAD:' + IDL.relative_to('brave').as_posix()], cwd=ROOT)
    (baseline_src/IDL).write_bytes(baseline_idl)
    checked_in = ROOT/'win_build_output/midl/chrome/elevation_service'

    def compile_idl(cwd, output, platform):
        output.mkdir(parents=True, exist_ok=True)
        command = [str(sdk_bin/'midl.exe'), '/nologo', '/char', 'signed',
                   '/env', platform, '/Oicf', '/tlb', FILES[4], '/h', FILES[0],
                   '/dlldata', FILES[3], '/iid', FILES[1], '/proxy', FILES[2],
                   '/cpp_cmd', str(compiler_bin/'cl.exe'), '/cpp_opt', '/E /nologo',
                   '../../' + IDL.as_posix(), '/out', str(output)]
        result = subprocess.run(command, cwd=cwd, env=env,
                                stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                                text=True, check=True)
        (output/'compiler.log').write_text(result.stdout)
        for file in FILES:
            midl_utils.ZapTimestamp(str(output/file))

    for arch, platform in [('x64', 'x64'), ('x86', 'win32'), ('arm64', 'arm64')]:
        baseline_out = args.work_dir/'baseline'/arch
        compile_idl(baseline_src/'out/Static', baseline_out, platform)
        for file in FILES:
            # Compare against HEAD, not a partially regenerated working tree.
            original = subprocess.check_output(['git', 'show',
                'HEAD:win_build_output/midl/chrome/elevation_service/' + arch + '/' + file], cwd=ROOT)
            generated = (baseline_out/file).read_bytes()
            if not file.endswith('.tlb'):
                original = original.replace(b'\r\n', b'\n')
                generated = generated.replace(b'\r\n', b'\n')
            assert generated == original, f'Baseline mismatch: {arch}/{file}'
        output = args.work_dir/'generated'/arch
        # script/ is the same depth as out/Static, preserving the canonical
        # relative IDL path embedded in the generated C/header files.
        compile_idl(ROOT/'script', output, platform)
        for file in FILES:
            shutil.copyfile(output/file, checked_in/arch/file)
        print(f'{arch}: baseline matched; five COM files regenerated by MIDL')
    for file in FILES:
        shutil.copyfile(checked_in/'x64'/file, checked_in/file)
    print('Default COM output mirrors x64.')


if __name__ == '__main__':
    main()
